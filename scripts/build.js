const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const read = file => fs.readFileSync(path.join(root,file),'utf8');
const write = (file,body) => { const target=path.join(root,file); fs.mkdirSync(path.dirname(target),{recursive:true}); fs.writeFileSync(target,body); };
const raw = 'https://raw.githubusercontent.com/yixiay/Surge-Modules/main/';
const variants = [
  {id:'mayihei',dir:'ipquality-mayihei',title:'IP 质量检测 · MaYIHEI',source:'vendor/mayihei/ipquality.js'},
  {id:'web',dir:'ipquality-web',title:'IP 质量检测 · Web 扩展',source:'vendor/paperclip-r32/ipquality.js'},
  {id:'xykt',dir:'ipquality-xykt',title:'IP 质量检测 · xykt 五库'}
];
for (const v of variants) {
  const dir='modules/network-diagnostics/'+v.dir;
  let body=read('src/panel-format.js')+'\n'+read('src/runtime.js').replace('__FLAVOR__',v.id).replace('__TITLE__',v.title);
  if (v.source) {
    let upstream=read(v.source);
    // Authorization errors are terminal: never replay backend 403 requests.
    upstream=upstream.replace(/if \(!\/HTTP 403\\b\/i\.test\(errorMessage\(error\)\) \|\| attempt >= 3\) throw error;/g,'throw error; // Surge port: do not replay authorization failures.');
    body+='\nfunction runLoon($done, $persistentStore, $environment, $httpClient) {\n'+upstream+'\n}\n';
    if(v.id==='web') body+='\nfunction runSpeed($done, $persistentStore, $request, $httpClient) {\n'+read('vendor/bobo-web/speed.js')+'\n}\n';
  } else body+='\n'+read('src/xykt.js');
  write(dir+'/report.js','// Generated by npm run build; edit src/ and vendor/ instead.\n'+body);
  const params='policy={{{policy_group}}}&mask={{{mask_ip}}}'+(v.id==='mayihei'?'&media={{{media_test}}}':'');
  const script=raw+dir+'/report.js';
  write(dir+'/module.sgmodule',`#!name=${v.title}
#!desc=彩色 HTML 详细报告：http://ipquality.surge.local/${v.id} 。面板可手动生成报告。无需 MITM。
#!category=网络诊断
#!arguments=policy_group:✈️ 我的节点（所有订阅）,mask_ip:false${v.id==='mayihei'?',media_test:false':''}
#!arguments-desc=填写现有节点或策略组；mask_ip 控制隐藏出口 IP。${v.id==='mayihei'?'media_test 控制流媒体检测。':'通过报告页按钮按需检测。'}
#!homepage=https://github.com/yixiay/Surge-Modules

[Host]
ipquality.surge.local = 127.0.0.1

[Script]
ipquality-${v.id}-panel = type=generic,script-path=${script},argument="${params}",timeout=55
ipquality-${v.id}-report = type=http-request,pattern=^http://ipquality\\.surge\\.local/${v.id}(?:/|$|\\?),script-path=${script},argument="${params}",timeout=55,requires-body=false

[Panel]
ipquality-${v.id} = script-name=ipquality-${v.id}-panel,update-interval=3600
`);
}
